// Generates src/md/tokens.css: Material 3 color roles (light + dark) from one seed color.
// Run at build time only (`npm run theme`); the output is plain CSS custom properties.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  argbFromHex,
  hexFromArgb,
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
} from '@material/material-color-utilities';

const SEED = process.env.VIEWER_HUB_SEED || '#3557a7';
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'md', 'tokens.css');

const roles = Object.getOwnPropertyNames(MaterialDynamicColors).filter(
  (name) => !name.endsWith('PaletteKeyColor') && typeof MaterialDynamicColors[name]?.getArgb === 'function',
);
const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function block(isDark) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), isDark, 0);
  return roles
    .map((name) => `  --md-sys-color-${kebab(name)}: ${hexFromArgb(MaterialDynamicColors[name].getArgb(scheme))};`)
    .join('\n');
}

const light = block(false);
const dark = block(true);
const css = `/* Generated by scripts/make-theme.mjs from seed ${SEED}. Do not edit by hand. */
:root {
  color-scheme: light;
${light}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${dark.replace(/^/gm, '  ')}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${dark}
}
`;
writeFileSync(out, css);
console.log(`tokens.css: ${roles.length} roles from ${SEED}`);
