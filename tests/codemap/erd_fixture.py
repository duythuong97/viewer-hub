"""A code-map output with foreign keys, built from a copy of the code-map demo (the demo itself is never touched).

The copy is first reset to an old-style extract (no REFERENCES edge, only the demo's two original primary
keys), then gets primary keys and FKs the way the new extractor writes them (one edge per column pair, properties constraint/position/source/delete_rule/...):

    ORDER_LINE.ORDER_ID              -> ORDERS.ORDER_ID            FK_ORDER_LINE_ORDER   ON DELETE CASCADE
    SHIPMENT.ORDER_ID                -> ORDERS.ORDER_ID            FK_SHIPMENT_ORDER     NO ACTION
    PAYMENT_TRANSACTION.ORDER_ID     -> ORDERS.ORDER_ID            FK_PAYMENT_ORDER      (from DDL)
    BACKORDER.ORDER_ID               -> ORDERS.ORDER_ID            FK_BACKORDER_ORDER
    ORDER_HEADER.ORDER_ID            -> ORDERS.ORDER_ID            FK_ORDER_HEADER_ORDER (one-to-one: also the PK)
    ORDER_HEADER.CUSTOMER_ID         -> DB2 CUSTOMERS.CUSTOMER_ID  FK_ORDER_HEADER_CUSTOMER
    SHIPMENT_PACKAGE.SHIPMENT_ID     -> SHIPMENT.SHIPMENT_ID       FK_PACKAGE_SHIPMENT
    SHIPMENT_AUDIT.SHIPMENT_ID       -> SHIPMENT.SHIPMENT_ID       FK_AUDIT_SHIPMENT     ON DELETE SET NULL
    INVENTORY_RESERVATION.(ORDER_ID, PRODUCT_ID) -> ORDER_LINE.(ORDER_ID, PRODUCT_ID)  FK_RESERVATION_LINE (composite)

Dev data dir for the browser:  python tests/codemap/erd_fixture.py <data dir>
"""
from __future__ import annotations

import json
import os
import shutil
import sqlite3
import sys
from pathlib import Path

DEMO = Path(os.environ.get("CODEMAP_DEMO", "/Volumes/thuong.pham/sources/code-map/var/output/demo"))
FILES = ("codemap.sqlite", "graph.sqlite", "manifest.json", "quality-report.json")

ORIGINAL_KEYS = {"column:DB1:ORDERS:ORDER_ID", "column:DB2:CUSTOMERS:CUSTOMER_ID"}
PRIMARY_KEYS = [
    "column:DB1:ORDER_LINE:ORDER_LINE_ID", "column:DB1:SHIPMENT:SHIPMENT_ID", "column:DB1:PAYMENT_TRANSACTION:PAYMENT_ID",
    "column:DB1:BACKORDER:BACKORDER_ID", "column:DB1:SHIPMENT_PACKAGE:PACKAGE_ID", "column:DB1:SHIPMENT_AUDIT:AUDIT_ID",
    "column:DB1:INVENTORY_RESERVATION:RESERVATION_ID", "column:DB1:FULFILLMENT_ALLOCATION:ALLOCATION_ID",
    "column:DB1:ORDER_HEADER:ORDER_ID",
]
# (constraint, [(fk column, referenced column)], source, delete_rule, referenced constraint)
FOREIGN_KEYS = [
    ("FK_ORDER_LINE_ORDER", [("DB1:ORDER_LINE:ORDER_ID", "DB1:ORDERS:ORDER_ID")], "catalog", "CASCADE", "PK_ORDERS"),
    ("FK_SHIPMENT_ORDER", [("DB1:SHIPMENT:ORDER_ID", "DB1:ORDERS:ORDER_ID")], "catalog", "NO ACTION", "PK_ORDERS"),
    ("FK_PAYMENT_ORDER", [("DB1:PAYMENT_TRANSACTION:ORDER_ID", "DB1:ORDERS:ORDER_ID")], "ddl", "", ""),
    ("FK_BACKORDER_ORDER", [("DB1:BACKORDER:ORDER_ID", "DB1:ORDERS:ORDER_ID")], "catalog", "NO ACTION", "PK_ORDERS"),
    ("FK_ORDER_HEADER_ORDER", [("DB1:ORDER_HEADER:ORDER_ID", "DB1:ORDERS:ORDER_ID")], "catalog", "NO ACTION", "PK_ORDERS"),
    ("FK_ORDER_HEADER_CUSTOMER", [("DB1:ORDER_HEADER:CUSTOMER_ID", "DB2:CUSTOMERS:CUSTOMER_ID")], "catalog", "NO ACTION", "PK_CUSTOMERS"),
    ("FK_PACKAGE_SHIPMENT", [("DB1:SHIPMENT_PACKAGE:SHIPMENT_ID", "DB1:SHIPMENT:SHIPMENT_ID")], "catalog", "NO ACTION", "PK_SHIPMENT"),
    ("FK_AUDIT_SHIPMENT", [("DB1:SHIPMENT_AUDIT:SHIPMENT_ID", "DB1:SHIPMENT:SHIPMENT_ID")], "catalog", "SET NULL", "PK_SHIPMENT"),
    ("FK_RESERVATION_LINE", [("DB1:INVENTORY_RESERVATION:ORDER_ID", "DB1:ORDER_LINE:ORDER_ID"),
                             ("DB1:INVENTORY_RESERVATION:PRODUCT_ID", "DB1:ORDER_LINE:PRODUCT_ID")], "catalog", "NO ACTION", "UK_ORDER_LINE_PRODUCT"),
]


def clear_foreign_keys(database: Path) -> None:
    """No REFERENCES edge and no primary-key flag but the demo's original two: what an older extract looks like.

    The demo is regenerated by code-map (a newer extractor writes its own REFERENCES edges and keys), so the
    copy is reset first and the fixture stays the same whatever the demo currently holds.
    """
    with sqlite3.connect(database) as db:
        db.execute("DELETE FROM graph_edges WHERE edge_type='REFERENCES'")
        for node_id, props_json in db.execute("SELECT node_id, properties_json FROM graph_nodes WHERE node_type='COLUMN'").fetchall():
            props = json.loads(props_json)
            wanted = "Y" if node_id in ORIGINAL_KEYS else ""
            if props.get("primary_key", "") != wanted:
                props["primary_key"] = wanted
                db.execute("UPDATE graph_nodes SET properties_json=? WHERE node_id=?", (json.dumps(props), node_id))


def add_foreign_keys(database: Path) -> None:
    """Primary-key flags and REFERENCES edges in a copy of the demo codemap.sqlite."""
    with sqlite3.connect(database) as db:
        for node_id in PRIMARY_KEYS:
            row = db.execute("SELECT properties_json FROM graph_nodes WHERE node_id=?", (node_id,)).fetchone()
            assert row, node_id
            props = json.loads(row[0])
            props["primary_key"] = "Y"
            db.execute("UPDATE graph_nodes SET properties_json=? WHERE node_id=?", (json.dumps(props), node_id))
        for constraint, pairs, source, delete_rule, referenced in FOREIGN_KEYS:
            for position, (fk_column, pk_column) in enumerate(pairs, start=1):
                for column in (fk_column, pk_column):
                    assert db.execute("SELECT 1 FROM graph_nodes WHERE node_id=?", (f"column:{column}",)).fetchone(), column
                props = {"constraint": constraint, "position": position, "source": source, "delete_rule": delete_rule,
                         "referenced_constraint": referenced}
                db.execute(
                    "INSERT INTO graph_edges(edge_id,source_node_id,target_node_id,edge_type,graph_layer,raw_operation,confidence,"
                    "properties_json,source_id) VALUES(?,?,?,?,?,?,?,?,?)",
                    (f"edge:fk:{constraint}:{position}", f"column:{fk_column}", f"column:{pk_column}", "REFERENCES", "STRUCTURAL",
                     "", 1.0, json.dumps(props), "test:erd-fixture"),
                )


def make_output(target: Path, *, foreign_keys: bool = True) -> Path:
    """Copy the demo output files to ``target`` (a code-map output folder) and add the FKs."""
    target.mkdir(parents=True, exist_ok=True)
    for name in FILES:
        if (DEMO / name).is_file():
            shutil.copy2(DEMO / name, target / name)
    clear_foreign_keys(target / "codemap.sqlite")
    if foreign_keys:
        add_foreign_keys(target / "codemap.sqlite")
    return target


if __name__ == "__main__":
    # A data dir whose dev folder <home>/codemap is the fixture (served as pack "local").
    home = Path(sys.argv[1])
    make_output(home / "codemap")
    print(home / "codemap")
